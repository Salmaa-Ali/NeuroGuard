package com.neuroguard.imaging;

import com.fasterxml.jackson.databind.JsonNode;
import com.neuroguard.appointment.entity.Appointment;
import com.neuroguard.appointment.entity.AppointmentStatus;
import com.neuroguard.appointment.repository.AppointmentRepository;
import com.neuroguard.patient.entity.Patient;
import com.neuroguard.staff.entity.Staff;
import com.neuroguard.support.AbstractIntegrationTest;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.test.web.servlet.ResultActions;
import org.springframework.test.web.servlet.request.MockMvcRequestBuilders;

import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/** MRI orders: Neurologist creates, MRI tech updates status; accession numbers are generated by the server. */
class MriOrderTest extends AbstractIntegrationTest {

    private static final String URL = "/api/mri-orders";
    private static final String FORMAT = "ACC-\\d{4}-\\d{6,}";

    @Autowired
    private AppointmentRepository appointmentRepository;

    private Appointment appointmentA;

    @BeforeEach
    void appointment() {
        appointmentA = appointment(patientA, AppointmentStatus.SCHEDULED);
    }

    private Appointment appointment(Patient p, AppointmentStatus status) {
        Appointment a = new Appointment();
        a.setPatient(p);
        a.setStaff(neurologist);
        a.setScheduledTime(Instant.now().plus(1, ChronoUnit.DAYS).truncatedTo(ChronoUnit.MICROS));
        a.setStatus(status);
        a.setReason("TEST reason");
        return appointmentRepository.saveAndFlush(a);
    }

    private static Map<String, Object> body(Appointment a) {
        Map<String, Object> body = new HashMap<>();
        body.put("appointmentId", a.getId().toString());
        body.put("indication", "TEST indication");
        return body;
    }

    private JsonNode create(Appointment a) throws Exception {
        String json = postJson(URL, bearer(neurologist), body(a))
                .andExpect(status().isCreated()).andReturn().getResponse().getContentAsString();
        return objectMapper.readTree(json);
    }

    private static long seq(String accession) {
        return Long.parseLong(accession.substring(accession.lastIndexOf('-') + 1));
    }

    private ResultActions patchStatus(String id, Staff s, String status) throws Exception {
        return mockMvc.perform(MockMvcRequestBuilders.patch(URL + "/" + id + "/status")
                .header("Authorization", bearer(s))
                .contentType("application/json")
                .content(objectMapper.writeValueAsString(Map.of("status", status))));
    }

    private int auditCount(String action, String entityId) {
        return jdbc.queryForObject("""
                SELECT count(*) FROM audit_log WHERE action = ? AND entity_type = 'MRI_ORDER'
                  AND entity_id = ?::uuid AND actor_type = 'STAFF'
                """, Integer.class, action, entityId);
    }

    @Test
    void neurologistCreatesOrderWithGeneratedAccessionNumber() throws Exception {
        postJson(URL, bearer(neurologist), body(appointmentA))
                .andExpect(status().isCreated())
                .andExpect(header().string("Location", org.hamcrest.Matchers.startsWith("/api/mri-orders/")))
                .andExpect(jsonPath("$.accessionNumber").value(org.hamcrest.Matchers.matchesPattern(FORMAT)))
                .andExpect(jsonPath("$.status").value("ORDERED"))
                .andExpect(jsonPath("$.indication").value("TEST indication"));
    }

    @Test
    void yearIsTheCreationYearInUtc() throws Exception {
        testClock.setInstant(Instant.parse("2027-01-01T00:30:00Z"));
        assertTrue(create(appointmentA).get("accessionNumber").asText().startsWith("ACC-2027-"));
        testClock.setInstant(Instant.parse("2026-12-31T23:59:00Z"));
        assertTrue(create(appointmentA).get("accessionNumber").asText().startsWith("ACC-2026-"));
    }

    @Test
    void twoOrdersGetDifferentIncreasingNumbers() throws Exception {
        String first = create(appointmentA).get("accessionNumber").asText();
        String second = create(appointmentA).get("accessionNumber").asText();
        assertTrue(seq(second) > seq(first), first + " then " + second);
    }

    @Test
    void accessionNumberInTheRequestIsIgnored() throws Exception {
        Map<String, Object> body = body(appointmentA);
        body.put("accessionNumber", "MY-OWN-123");
        String accession = objectMapper.readTree(postJson(URL, bearer(neurologist), body)
                .andExpect(status().isCreated()).andReturn().getResponse().getContentAsString())
                .get("accessionNumber").asText();
        assertTrue(accession.matches(FORMAT), accession);
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM mri_order WHERE accession_number = 'MY-OWN-123'",
                Integer.class));
    }

    @Test
    void patientOnTheOrderIsAlwaysTheAppointmentsPatient() throws Exception {
        Map<String, Object> body = body(appointmentA);
        body.put("patientId", patientB.getId().toString());
        postJson(URL, bearer(neurologist), body)
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.patientId").value(patientA.getId().toString()));
    }

    @Test
    void cancelledOrMissedAppointmentCannotBeOrderedOn() throws Exception {
        for (AppointmentStatus st : List.of(AppointmentStatus.CANCELLED, AppointmentStatus.MISSED)) {
            assertStandardError(postJson(URL, bearer(neurologist), body(appointment(patientA, st))), 409);
        }
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM mri_order", Integer.class));
    }

    @Test
    void completedAppointmentCanBeOrderedOn() throws Exception {
        create(appointment(patientA, AppointmentStatus.COMPLETED));
    }

    @Test
    void unknownAppointmentGets404() throws Exception {
        Map<String, Object> body = body(appointmentA);
        body.put("appointmentId", "00000000-0000-0000-0000-000000000000");
        assertStandardError(postJson(URL, bearer(neurologist), body), 404);
    }

    @Test
    void missingAppointmentGets400() throws Exception {
        assertStandardError(postJson(URL, bearer(neurologist), Map.of("indication", "TEST")), 400);
    }

    @Test
    void onlyNeurologistCanCreate() throws Exception {
        for (Staff s : List.of(admin, radiologist, mriTech, biomedEngineer, billingClerk)) {
            assertStandardError(postJson(URL, bearer(s), body(appointmentA)), 403);
        }
        assertStandardError(postJson(URL, bearer(patientA), body(appointmentA)), 403);
        assertEquals(0, jdbc.queryForObject("SELECT count(*) FROM mri_order", Integer.class));
    }

    @Test
    void creationAndStatusChangeAreAudited() throws Exception {
        String id = create(appointmentA).get("id").asText();
        assertEquals(1, auditCount("MRI_ORDER_CREATED", id));

        patchStatus(id, mriTech, "SCHEDULED").andExpect(status().isOk()).andExpect(jsonPath("$.status").value("SCHEDULED"));
        assertEquals(1, auditCount("MRI_ORDER_STATUS_CHANGED", id));
        assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM audit_log WHERE action = 'MRI_ORDER_STATUS_CHANGED'"
                + " AND actor_id = ?", Integer.class, mriTech.getId()));
    }

    @Test
    void onlyMriTechCanChangeStatus() throws Exception {
        String id = create(appointmentA).get("id").asText();
        for (Staff s : List.of(neurologist, radiologist, admin, billingClerk)) {
            assertStandardError(patchStatus(id, s, "SCHEDULED"), 403);
        }
        assertEquals(0, auditCount("MRI_ORDER_STATUS_CHANGED", id));
    }
}
